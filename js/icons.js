export function icon(name, size = 18) {
    const d = paths[name];
    if (!d) return '';
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none"
        stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"
        class="icon-svg" aria-hidden="true" focusable="false">${d}</svg>`;
}

/** Ersetzt alle `<span class="js-icon" data-icon="…">` im Dokument (oder Teilbaum). */
export function hydrateIcons(root = document) {
    root.querySelectorAll('.js-icon[data-icon]').forEach(el => {
        const size = Number(el.dataset.size) || 18;
        el.innerHTML = icon(el.dataset.icon, size);
    });
}

